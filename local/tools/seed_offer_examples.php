function tacticum_offer_seed_budget(array $sector, array $useCase, array $scale, array $phase, int $index): int
{
    $baseByComplexity = [
        1 => 700000,
        2 => 1800000,
        3 => 4800000,
        4 => 11500000,
        5 => 28500000,
    ];
    $complexity = (int)($useCase['complexity'] ?? 3);
    $base = $baseByComplexity[$complexity] ?? $baseByComplexity[3];
    $variation = 1 + (((($index + 11) * 37) % 17) - 8) / 100;

    return tacticum_offer_seed_round_budget(
        $base
        * (float)$sector['multiplier']
        * (float)$scale['multiplier']
        * (float)$phase['multiplier']
        * $variation
    );
}


function tacticum_offer_seed_available_properties(int $iblockId): array
{
    $properties = [];
    $result = CIBlockProperty::GetList([], ['IBLOCK_ID' => $iblockId]);
    while ($property = $result->Fetch()) {
        $code = trim((string)($property['CODE'] ?? ''));
        if ($code !== '') {
            $properties[$code] = true;
        }
    }

    return $properties;
}

function tacticum_offer_seed_find_existing(int $iblockId, string $code, string $groupId): ?array
{
    foreach ([['=CODE' => $code], ['=PROPERTY_GROUP_ID' => $groupId]] as $filterPart) {
        $result = CIBlockElement::GetList(
            [],
            array_merge(['IBLOCK_ID' => $iblockId], $filterPart),
            false,
            ['nTopCount' => 1],
            ['ID', 'IBLOCK_ID', 'NAME', 'CODE', 'ACTIVE']
        );
        $element = $result->Fetch();
        if ($element) {
            return $element;
        }
    }

    return null;
}

function tacticum_offer_seed_create(int $iblockId, array $offer, string $active): int
{
    $element = new CIBlockElement();
    $id = $element->Add([
        'IBLOCK_ID' => $iblockId,
        'NAME' => $offer['name'],
        'CODE' => $offer['code'],
        'ACTIVE' => $active,
        'DATE_ACTIVE_FROM' => $offer['created_at'],
        'SORT' => 500 + (int)$offer['case_number'],
        'PREVIEW_TEXT' => trim(strip_tags((string)$offer['properties']['SUMMARY'])),
        'PREVIEW_TEXT_TYPE' => 'text',
        'DETAIL_TEXT' => (string)$offer['properties']['SUMMARY'],
        'DETAIL_TEXT_TYPE' => 'html',
        'PROPERTY_VALUES' => $offer['properties'],
    ]);

    if (!$id) {
        tacticum_offer_seed_fail('Failed to create element "' . $offer['code'] . '": ' . $element->LAST_ERROR);
    }

    return (int)$id;
}

function tacticum_offer_seed_update(int $iblockId, int $elementId, array $offer, string $active): void
{
    $element = new CIBlockElement();
    $ok = $element->Update($elementId, [
        'NAME' => $offer['name'],
        'CODE' => $offer['code'],
        'ACTIVE' => $active,
        'DATE_ACTIVE_FROM' => $offer['created_at'],
        'SORT' => 500 + (int)$offer['case_number'],
        'PREVIEW_TEXT' => trim(strip_tags((string)$offer['properties']['SUMMARY'])),
        'PREVIEW_TEXT_TYPE' => 'text',
        'DETAIL_TEXT' => (string)$offer['properties']['SUMMARY'],
        'DETAIL_TEXT_TYPE' => 'html',
    ]);
    if (!$ok) {
        tacticum_offer_seed_fail('Failed to update element #' . $elementId . ': ' . $element->LAST_ERROR);
    }

    CIBlockElement::SetPropertyValuesEx($elementId, $iblockId, $offer['properties']);
}

$options = getopt('', [
    'limit::',
    'offset::',
    'apply',
    'update-existing',
    'active::',
    'help',
]);

if (isset($options['help'])) {
    echo tacticum_offer_seed_usage();
    exit(0);
}

$limit = tacticum_offer_seed_option_int($options, 'limit', TACTICUM_OFFER_SEED_TOTAL, 1, TACTICUM_OFFER_SEED_TOTAL);
$offset = tacticum_offer_seed_option_int($options, 'offset', 0, 0, TACTICUM_OFFER_SEED_TOTAL - 1);
if ($offset + $limit > TACTICUM_OFFER_SEED_TOTAL) {
    tacticum_offer_seed_fail('Invalid range: --offset + --limit must be <= ' . TACTICUM_OFFER_SEED_TOTAL . '.');
}

$active = strtoupper((string)($options['active'] ?? 'Y'));
if (!in_array($active, ['Y', 'N'], true)) {
    tacticum_offer_seed_fail('Invalid --active; expected Y or N.');
}

$apply = array_key_exists('apply', $options);
$updateExisting = array_key_exists('update-existing', $options);

if (!Loader::includeModule('iblock')) {
    tacticum_offer_seed_fail('Bitrix iblock module is not available.');
}
if (!function_exists('tacticum_iblock_id')) {
    tacticum_offer_seed_fail('tacticum_iblock_id() is not available. Check local/php_interface/init.php bootstrap.');
}

$iblockId = tacticum_iblock_id('offer');
if ($iblockId <= 0) {
    tacticum_offer_seed_fail('Offer iblock is not configured.');
}

$requiredProperties = [
    'IS_FINAL',
    'GROUP_ID',
    'RESPONSE_ID',
    'RESPONSE',
    'SUMMARY',
    'GOALS',
    'BUSINESS_CONTEXT',
    'FUNCTIONAL_REQUIREMENTS',
    'NONFUNCTIONAL_REQUIREMENTS',
    'TEAM',
    'STACK',
    'BUDGET',
    'TIMELINE',
    'CLIENT_NAME',
    'TITLE',
    'DESCRIPTION',
    'KEYWORDS',
    'H1',
    'TECH_RISKS',
    'BUSINESS_RISKS',
];
$availableProperties = tacticum_offer_seed_available_properties($iblockId);
$missingProperties = array_values(array_filter(
    $requiredProperties,
    static fn(string $code): bool => !isset($availableProperties[$code])
));
if ($missingProperties !== []) {
    tacticum_offer_seed_fail('Offer iblock is missing required properties: ' . implode(', ', $missingProperties));
}

$stats = [
    'generated' => 0,
    'created' => 0,
    'updated' => 0,
    'skipped_existing' => 0,
    'dry_run_new' => 0,
    'dry_run_existing' => 0,
    'min_budget' => PHP_INT_MAX,
    'max_budget' => 0,
];
$samples = [];

for ($index = $offset; $index < $offset + $limit; $index++) {
    $offer = tacticum_offer_seed_build_offer($index);
    $stats['generated']++;
    $stats['min_budget'] = min($stats['min_budget'], (int)$offer['budget_amount']);
    $stats['max_budget'] = max($stats['max_budget'], (int)$offer['budget_amount']);

    if (count($samples) < 5) {
        $samples[] = sprintf(
            '#%04d | %s | %s | %s | %s',
            (int)$offer['case_number'],
            $offer['created_at'],
            $offer['properties']['BUDGET'],
            $offer['properties']['H1'],
            $offer['url']
        );
    }

    $existing = tacticum_offer_seed_find_existing(
        $iblockId,
        (string)$offer['code'],
        (string)$offer['properties']['GROUP_ID']
    );

    if (!$apply) {
        if ($existing) {
            $stats['dry_run_existing']++;
        } else {
            $stats['dry_run_new']++;
        }
        continue;
    }

    if ($existing) {
        if (!$updateExisting) {
            $stats['skipped_existing']++;
            continue;
        }

        tacticum_offer_seed_update($iblockId, (int)$existing['ID'], $offer, $active);
        $stats['updated']++;
        continue;
    }

    tacticum_offer_seed_create($iblockId, $offer, $active);
    $stats['created']++;
}

echo 'Offer examples seed' . PHP_EOL;
echo 'Mode: ' . ($apply ? 'apply' : 'dry-run') . PHP_EOL;
echo 'Iblock key: offer, resolved ID: ' . $iblockId . PHP_EOL;
echo 'Range: offset=' . $offset . ', limit=' . $limit . ', active=' . $active . PHP_EOL;
echo 'Generated: ' . $stats['generated'] . PHP_EOL;
echo 'Created: ' . $stats['created'] . PHP_EOL;
echo 'Updated: ' . $stats['updated'] . PHP_EOL;
echo 'Skipped existing: ' . $stats['skipped_existing'] . PHP_EOL;
echo 'Dry-run new: ' . $stats['dry_run_new'] . PHP_EOL;
echo 'Dry-run existing: ' . $stats['dry_run_existing'] . PHP_EOL;
echo 'Budget range: ' . tacticum_offer_seed_money($stats['min_budget']) . ' - ' . tacticum_offer_seed_money($stats['max_budget']) . PHP_EOL;
echo 'Samples:' . PHP_EOL;
foreach ($samples as $sample) {
    echo '  ' . $sample . PHP_EOL;
}
if (!$apply) {
    echo 'No writes performed. Re-run with --apply to create elements.' . PHP_EOL;
}

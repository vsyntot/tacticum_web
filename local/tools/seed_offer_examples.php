    if ($budget <= 75000000) {
        return '6-9 месяцев';
    }

    return (string)($phase['long_timeline'] ?? '9-12 месяцев');
}

function tacticum_offer_seed_created_at(int $caseNumber): DateTimeImmutable
{
    $timezone = new DateTimeZone('Europe/Moscow');
    $start = DateTimeImmutable::createFromFormat('!Ymd-His', TACTICUM_OFFER_SEED_START_TIME, $timezone);
    $end = DateTimeImmutable::createFromFormat('!Ymd-His', TACTICUM_OFFER_SEED_END_TIME, $timezone);
    if ($start === false || $end === false) {
        tacticum_offer_seed_fail('Invalid seed date range.');
    }

    if ($caseNumber <= 1) {
        return $start;
    }
    if ($caseNumber >= TACTICUM_OFFER_SEED_TOTAL) {
        return $end;
    }

    $interval = $end->getTimestamp() - $start->getTimestamp();
    $step = $interval / max(1, TACTICUM_OFFER_SEED_TOTAL - 1);
    $baseTimestamp = (int)round($start->getTimestamp() + ($step * ($caseNumber - 1)));
    $jitter = (($caseNumber * 7919) % 79200) - 39600;
    $timestamp = max($start->getTimestamp(), min($end->getTimestamp(), $baseTimestamp + $jitter));

    return (new DateTimeImmutable('@' . $timestamp))->setTimezone($timezone);
}

function tacticum_offer_seed_code(string $title, int $caseNumber, DateTimeImmutable $createdAt): string
{
    $base = CUtil::translit($title, 'ru', [
        'replace_space' => '-',
        'replace_other' => '-',
        'change_case' => 'L',
    ]);
    $base = trim((string)$base, '-');
    if ($base === '') {
        $base = 'primer-rascheta-proekta';
    }

    $suffix = '-' . $createdAt->format('Ymd-His');
    $maxBaseLength = 100 - mb_strlen($suffix);
    $base = rtrim(mb_substr($base, 0, $maxBaseLength), '-');

    return $base . $suffix;
}


function tacticum_offer_seed_fail(string $message, int $code = 1): never
{
    fwrite(STDERR, $message . PHP_EOL);
    exit($code);
}

function tacticum_offer_seed_option_int(array $options, string $name, int $default, int $min, int $max): int
{
    $raw = $options[$name] ?? $default;
    if (is_array($raw) || filter_var($raw, FILTER_VALIDATE_INT) === false) {
        tacticum_offer_seed_fail("Invalid --{$name}; expected integer.");
    }

    $value = (int)$raw;
    if ($value < $min || $value > $max) {
        tacticum_offer_seed_fail("Invalid --{$name}; expected {$min}..{$max}.");
    }

    return $value;
}

function tacticum_offer_seed_pick(array $items, int $index, int $step = 1): array|string
{
    if ($items === []) {
        tacticum_offer_seed_fail('Generator dictionary is empty.');
    }

    return $items[($index * $step) % count($items)];
}

function tacticum_offer_seed_escape(string $value): string
{
    return htmlspecialchars($value, ENT_QUOTES | ENT_SUBSTITUTE, 'UTF-8');
}

function tacticum_offer_seed_ucfirst(string $value): string
{
    $value = trim($value);
    if ($value === '') {
        return '';
    }

    return mb_strtoupper(mb_substr($value, 0, 1)) . mb_substr($value, 1);
}

function tacticum_offer_seed_money(int $amount): string
{
    return number_format($amount, 0, '', ' ') . ' руб.';
}

function tacticum_offer_seed_round_budget(float $amount): int
{
    $amount = max(500000, min(150000000, (int)round($amount)));
    if ($amount < 2000000) {
        $step = 100000;
    } elseif ($amount < 10000000) {
        $step = 500000;
    } elseif ($amount < 50000000) {
        $step = 1000000;
    } else {
        $step = 5000000;
    }

    return max(500000, min(150000000, (int)(round($amount / $step) * $step)));
}

function tacticum_offer_seed_timeline(int $budget, array $phase): string
{
    if ($budget <= 1000000) {

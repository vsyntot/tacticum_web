    public static function normalizeArray(array $payload): array
    {
        foreach ($payload as $key => $value) {
            if (is_array($value)) {
                $payload[$key] = self::normalizeArray($value);
                continue;
            }
            if (is_string($value)) {
                $payload[$key] = self::normalizeString($value);
            }
        }

        return $payload;
    }

    public static function normalizePageContentSection(array $section): array
    {
        $section = self::normalizeArray($section);
        if (($section['page_key'] ?? '') !== '/about/') {
            return $section;
        }

        $sectionKey = (string)($section['section_key'] ?? '');
        if (isset(self::ABOUT_PAGE_CONTENT_SECTIONS[$sectionKey])) {
            $section = array_replace($section, self::ABOUT_PAGE_CONTENT_SECTIONS[$sectionKey]);
        }

        if (isset(self::ABOUT_PAGE_CONTENT_BLOCKS[$sectionKey]) && isset($section['blocks']) && is_array($section['blocks'])) {
            foreach ($section['blocks'] as $index => $block) {
                if (!is_array($block)) {
                    continue;
                }
                $blockKey = (string)($block['block_key'] ?? $block['code'] ?? '');
                if (!isset(self::ABOUT_PAGE_CONTENT_BLOCKS[$sectionKey][$blockKey])) {
                    continue;
                }
                $section['blocks'][$index] = array_replace($block, self::ABOUT_PAGE_CONTENT_BLOCKS[$sectionKey][$blockKey]);
            }
        }

        return $section;
    }

    public static function normalizeString(string $value): string
    {
        return str_replace(array_keys(self::REPLACEMENTS), array_values(self::REPLACEMENTS), $value);
    }
